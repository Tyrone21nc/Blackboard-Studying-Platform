from django.db import models

class Course(models.Model):
    name = models.CharField(max_length=255)                     # e.g., "Data Structures"
    code = models.CharField(max_length=50, unique=True)         # e.g., "CMSC420". class code
    target_grade = models.CharField(max_length=2, default='A')  # 'A', 'B', or 'C'
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"{self.code}: {self.name}"

class GradeRecord(models.Model):
    course = models.ForeignKey(Course, on_delete=models.CASCADE, related_name='grades')
    assignment_name = models.CharField(max_length=255)
    weight = models.FloatField(default=0.0)                  # Percentage weight (e.g., 20.0 for 20%)
    score = models.FloatField(null=True, blank=True)         # Earned points or percentage
    points_possible = models.FloatField(null=True, blank=True)
    category = models.CharField(max_length=100, blank=True)  # e.g., "Homework", "Exam"

    def __str__(self):
        return f"{self.course.code} - {self.assignment_name}"

class CourseMaterial(models.Model):
    COURSE_MATERIAL_TYPES = [
        ('syllabus', 'Syllabus'),
        ('lecture', 'Lecture Notes'),
        ('homework', 'Homework Description'),
        ('other', 'Other Material'),
    ]
    course = models.ForeignKey(Course, on_delete=models.CASCADE, related_name='materials')
    title = models.CharField(max_length=255)
    material_type = models.CharField(max_length=20, choices=COURSE_MATERIAL_TYPES, default='other')
    text_content = models.TextField()                        # Scraped text content from Blackboard
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"[{self.material_type.upper()}] {self.title} ({self.course.code})"

class StudyPlan(models.Model):
    course = models.ForeignKey(Course, on_delete=models.CASCADE, related_name='study_plans')
    target_grade_goal = models.CharField(max_length=2)       # 'A', 'B', 'C'
    plan_content = models.TextField()                        # Markdown text generated by Gemini showing what scores are needed & study steps
    generated_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"Study Plan for {self.course.code} (Target: {self.target_grade_goal})"

class ChatMessage(models.Model):
    course = models.ForeignKey(Course, on_delete=models.CASCADE, related_name='chats', null=True, blank=True)
    sender = models.CharField(max_length=10)                 # 'user' or 'ai'
    message = models.TextField()
    timestamp = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"[{self.sender.upper()}] {self.message[:30]}..."